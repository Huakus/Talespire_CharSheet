// @vitest-environment happy-dom
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { openCharacterBuilder } from "../../src/ui/character-builder";
import { CampaignApplication } from "../../src/application/campaign/campaign-application";
import { InMemoryCampaignRepository } from "../../src/infrastructure/persistence/in-memory-campaign-repository";
import { createGuidedFighter, advanceGuidedFighter } from "../../src/domain/character/fighter-builder";
import { defaultFighterCreation } from "../../src/domain/character/fighter-builder-catalog";
import { BrowserApp } from "../../src/ui/browser-app";

const diceRoller = { roll: vi.fn(async () => ({ kind: "rolled" as const, summary: "d10: 8", totals: [8] })) };
const dialog = () => document.querySelector<HTMLDialogElement>(".character-builder-dialog")!;
const form = () => dialog().querySelector<HTMLFormElement>("form")!;
const field = (name: string) => form().querySelector<HTMLInputElement | HTMLSelectElement>(`[name="${name}"]`)!;
const dropdownButton = (name: string) => form().querySelector<HTMLButtonElement>(`[data-dialog-select="${name}"]`)!;
const set = (name: string, value: string) => { const control = field(name); control.value = value; control.dispatchEvent(new Event(control instanceof HTMLSelectElement ? "change" : "input", { bubbles: true })); };
const submit = () => form().dispatchEvent(new Event("submit", { bubbles: true, cancelable: true }));
const waitStage = async (title: string) => vi.waitFor(() => expect(dialog().querySelector('[aria-current="step"]')?.textContent, dialog().querySelector('[role="alert"]')?.textContent ?? "").toContain(title));
beforeEach(() => { localStorage.clear(); vi.clearAllMocks(); });
afterEach(async () => { dialog()?.close(); await new Promise((resolve) => setTimeout(resolve, 0)); document.body.replaceChildren(); });

describe("guided character user flow", () => {
  it("keeps a dropdown and its focus when the preceding text input commits on blur", async () => {
    await openCharacterBuilder({ campaignId: "dropdown-focus", diceRoller, onCreate: vi.fn(), onAdvance: vi.fn() });
    const name = field("name"), dropdown = field("classKey"), trigger = dropdownButton("classKey");
    name.focus(); set("name", "Ada");
    name.dispatchEvent(new Event("change", { bubbles: true }));
    trigger.focus();
    await new Promise((resolve) => setTimeout(resolve, 0));
    expect(field("classKey")).toBe(dropdown);
    expect(document.activeElement).toBe(trigger);
    expect(JSON.parse(localStorage.getItem("talespire-builder-v1:dropdown-focus:create")!).creation.name).toBe("Ada");
    set("classKey", "wizard");
    await vi.waitFor(() => expect(field("classKey").value).toBe("wizard"));
    submit(); await waitStage("Atributos");
    expect(field("ability_intelligence").value).toBe("15");
  });
  it("updates numeric feedback and initial-level navigation without replacing dropdowns", async () => {
    await openCharacterBuilder({ campaignId: "numeric-dropdown-focus", name: "Ada", diceRoller, onCreate: vi.fn(), onAdvance: vi.fn() });
    const dropdown = field("race"), startingLevel = field("startingLevel");
    startingLevel.value = "3"; startingLevel.dispatchEvent(new Event("change", { bubbles: true }));
    dropdownButton("race").focus();
    expect(dialog().querySelector("nav")!.textContent).toContain("Nivel 3");
    expect(field("race")).toBe(dropdown);
    startingLevel.value = "1"; startingLevel.dispatchEvent(new Event("change", { bubbles: true }));
    submit(); await waitStage("Atributos");
    set("abilityMethod", "rolled"); await vi.waitFor(() => expect(field("ability_strength")).toBeInstanceOf(HTMLInputElement));
    const method = field("abilityMethod"), strength = field("ability_strength");
    strength.value = "16"; strength.dispatchEvent(new Event("change", { bubbles: true })); dropdownButton("abilityMethod").focus();
    expect(dialog().querySelector('[data-builder-ability-total="strength"]')!.textContent).toContain("17");
    expect(field("abilityMethod")).toBe(method);
    expect(document.activeElement).toBe(dropdownButton("abilityMethod"));
  });
  it("updates the gold budget after numeric edits while preserving the purchase dropdown", async () => {
    await openCharacterBuilder({ campaignId: "budget-dropdown-focus", name: "Ada", diceRoller, onCreate: vi.fn(), onAdvance: vi.fn() });
    submit(); await waitStage("Atributos"); submit(); await waitStage("Formación"); submit(); await waitStage("Equipo");
    set("equipmentMethod", "gold"); await vi.waitFor(() => expect(field("goldDie0")).not.toBeNull());
    const dropdown = field("purchaseKey"), die = field("goldDie0");
    die.value = "4"; die.dispatchEvent(new Event("change", { bubbles: true })); dropdownButton("purchaseKey").focus();
    const draft = JSON.parse(localStorage.getItem("talespire-builder-v1:budget-dropdown-focus:create")!);
    const gold = draft.creation.equipment.goldRoll.reduce((a: number,b: number) => a+b,0)*10;
    expect(dialog().querySelector("[data-builder-gold-budget]")!.textContent).toContain(`Disponibles: ${gold} po`);
    expect(field("purchaseKey")).toBe(dropdown);
    expect(document.activeElement).toBe(dropdownButton("purchaseKey"));
  });
  it("keeps option lists inside the tutorial and removes them on close and resume", async () => {
    const options = { campaignId: "in-dialog-options", name: "Ada", diceRoller, onCreate: vi.fn(), onAdvance: vi.fn() };
    await openCharacterBuilder(options);
    dropdownButton("classKey").click();
    const classes = field("classKey") as HTMLSelectElement;
    expect(classes.size).toBeGreaterThan(1);
    expect(classes.closest<HTMLElement>(".dialog-select-panel")!.hidden).toBe(false);
    expect(dialog().contains(classes)).toBe(true);
    classes.value = "wizard"; classes.dispatchEvent(new Event("change", { bubbles: true }));
    await vi.waitFor(() => expect(dropdownButton("classKey").textContent).toContain("Mago"));
    dropdownButton("race").click();
    expect(field("race").closest<HTMLElement>(".dialog-select-panel")!.hidden).toBe(false);
    dialog().querySelector<HTMLButtonElement>("[data-builder-close]")!.click();
    await vi.waitFor(() => expect(document.querySelector(".dialog-select-panel")).toBeNull());
    await openCharacterBuilder(options);
    expect(field("classKey").value).toBe("wizard");
    expect([...dialog().querySelectorAll<HTMLElement>(".dialog-select-panel")].every((panel) => panel.hidden)).toBe(true);
  });
  it("creates a complete character from the five tutorial pages and removes its draft only after save", async () => {
    const application = new CampaignApplication(new InMemoryCampaignRepository());
    let snapshot = await application.createCampaign();
    const onCreate = vi.fn(async (operationId, creation) => { snapshot = await application.createGuidedCharacter({ operationId, creation, expectedCampaignChecksum: snapshot.checksum }); });
    await openCharacterBuilder({ campaignId: snapshot.campaign.id, diceRoller, onCreate, onAdvance: vi.fn() });
    set("name", "Ada");
    submit(); await waitStage("Atributos");
    expect(field("ability_strength").value).toBe("15");
    submit(); await waitStage("Formación");
    submit(); await waitStage("Equipo");
    set("prayerItem", "prayer-wheel"); await waitStage("Equipo");
    submit(); await waitStage("Revisar");
    expect(dialog().textContent).toContain("Cota de malla");
    expect(dialog().textContent).toContain("PG máximos");
    submit(); await vi.waitFor(() => expect(document.querySelector(".character-builder-dialog")).toBeNull());
    expect(onCreate).toHaveBeenCalledTimes(1);
    const character = Object.values(snapshot.campaign.characters)[0]!;
    expect(character.name).toBe("Ada");
    expect(character.actions.length).toBeGreaterThan(1);
    expect(character.builder?.creation.race).toBe("human");
    expect(character.inventory.some((item) => item.name === "Rueda de plegarias")).toBe(true);
    expect(localStorage.getItem(`talespire-builder-v1:${snapshot.campaign.id}:create`)).toBeNull();
  });
  it("keeps and resumes decisions across closing the dialog, including changed background presets", async () => {
    const options = { campaignId: "isolated-test", diceRoller, onCreate: vi.fn(), onAdvance: vi.fn() };
    await openCharacterBuilder(options);
    set("name", "Lina <elf>");
    submit(); await waitStage("Atributos");
    submit(); await waitStage("Formación");
    set("backgroundPreset", "sage");
    await vi.waitFor(() => expect(field("backgroundName").value).toBe("Sabio"));
    dialog().querySelector<HTMLButtonElement>("[data-builder-close]")!.click();
    await vi.waitFor(() => expect(document.querySelector(".character-builder-dialog")).toBeNull());
    await openCharacterBuilder(options);
    await waitStage("Formación");
    expect(field("backgroundName").value).toBe("Sabio");
    expect(dialog().textContent).toContain("Retomaste");
    dialog().querySelector<HTMLButtonElement>('[data-builder-step="0"]')!.click();
    await waitStage("Identidad");
    expect(field("name").value).toBe("Lina <elf>");
    expect(dialog().querySelector("elf")).toBeNull();
  });
  it("blocks invalid choices and preserves the review draft when persistence fails", async () => {
    const onCreate = vi.fn(async () => { throw new Error("La campaña cambió. Reabrí el borrador."); });
    await openCharacterBuilder({ campaignId: "failure-test", name: "Ada", diceRoller, onCreate, onAdvance: vi.fn() });
    submit(); await waitStage("Atributos");
    set("ability_strength", "14");
    await waitStage("Atributos"); submit();
    await vi.waitFor(() => expect(dialog().querySelector('[role="alert"]')?.textContent).toContain("Asigná"));
    expect(onCreate).not.toHaveBeenCalled();
    set("ability_strength", "15"); await waitStage("Atributos");
    submit(); await waitStage("Formación");
    submit(); await waitStage("Equipo");
    submit(); await waitStage("Revisar");
    submit(); await vi.waitFor(() => expect(dialog().querySelector('[role="alert"]')?.textContent).toContain("La campaña cambió"));
    expect(localStorage.getItem("talespire-builder-v1:failure-test:create")).not.toBeNull();
    expect(dialog().open).toBe(true);
  });
  it("uses the same review flow for subclass selection and rolls HP without changing the live sheet", async () => {
    let character = await createGuidedFighter("chr_11111111111111111111111111111111", "build_11111111111111111111111111111111", defaultFighterCreation("Ada"), "2026-10-12T12:00:00.000Z");
    character = await advanceGuidedFighter(character, { operationId: "build_22222222222222222222222222222222", level: 2, hpBase: 6, hpMethod: "fixed", abilityIncrease: null, subclass: null, additionalStyle: null }, "2026-10-12T12:00:00.000Z");
    const onAdvance = vi.fn(async (choice) => { character = await advanceGuidedFighter(character, choice, "2026-10-12T12:00:00.000Z"); });
    await openCharacterBuilder({ campaignId: "level-test", character, diceRoller, onCreate: vi.fn(), onAdvance });
    submit(); await vi.waitFor(() => expect(dialog().querySelector('[role="alert"]')?.textContent).toContain("Campeón"));
    set("subclass", "champion"); await waitStage("Nuevo nivel");
    set("hpMethod", "rolled"); await vi.waitFor(() => expect(field("hpBase")).not.toBeNull());
    dialog().querySelector<HTMLButtonElement>("[data-builder-roll]")!.click();
    await vi.waitFor(() => expect(field("hpBase").value).toBe("8"));
    submit(); await waitStage("Revisar");
    expect(character.identity.level).toBe(2);
    submit(); await vi.waitFor(() => expect(onAdvance).toHaveBeenCalledTimes(1));
    await vi.waitFor(() => expect(character.identity).toMatchObject({ level: 3, subclass: "Campeón" }));
  });
  it("exposes the tutorial from the real sheet management menu", async () => {
    const application = new CampaignApplication(new InMemoryCampaignRepository());
    const snapshot = await application.createCampaign();
    const root = document.createElement("div"); document.body.append(root);
    const app = new BrowserApp(root, application, { storageLabel: "test", diceRoller });
    const harness = app as unknown as { snapshot: typeof snapshot; render(): void };
    harness.snapshot = snapshot; harness.render();
    root.querySelector<HTMLButtonElement>("#create-guided-character")!.click();
    await vi.waitFor(() => expect(document.querySelector(".character-builder-dialog")).not.toBeNull());
    await waitStage("Identidad");
  });
  it("lets the player reach the background step to resolve duplicate language grants", async () => {
    await openCharacterBuilder({ campaignId: "duplicates-test", name: "Ada", diceRoller, onCreate: vi.fn(), onAdvance: vi.fn() });
    set("raceLanguage", "Élfico");
    submit(); await waitStage("Atributos");
    submit(); await waitStage("Formación");
    submit(); await vi.waitFor(() => expect(dialog().querySelector('[role="alert"]')?.textContent).toContain("idiomas"));
    set("backgroundLanguages", "Celestial, Enano");
    submit(); await waitStage("Equipo");
  });
  it("offers a racial replacement when a half-orc receives Intimidation from another source", async () => {
    const onCreate = vi.fn();
    await openCharacterBuilder({ campaignId: "racial-duplicate", name: "Orc", diceRoller, onCreate, onAdvance: vi.fn() });
    set("race", "half-orc"); await waitStage("Identidad");
    submit(); await waitStage("Atributos"); submit(); await waitStage("Formación");
    set("skill0", "intimidation"); await waitStage("Formación");
    expect(field("racialSkillReplacement")).not.toBeNull();
    set("racialSkillReplacement", "arcana"); await waitStage("Formación");
    submit(); await waitStage("Equipo"); submit(); await waitStage("Revisar");
    expect(dialog().textContent).toContain("Arcano");
    submit(); await vi.waitFor(() => expect(onCreate).toHaveBeenCalledTimes(1));
    expect(onCreate.mock.calls[0]![1].racialSkillReplacement).toBe("arcana");
  });
});
