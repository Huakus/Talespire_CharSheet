import { readFile, writeFile, mkdir } from 'node:fs/promises';

// Reuse the reviewed official assets and their complete license, offline.
const source = await readFile(new URL('../docs/v2/ui-redesign/compact-icon-sheet.html', import.meta.url), 'utf8');
const license = source.match(/<!-- (Lucide static[\s\S]*?)-->/)?.[1];
if (!license) throw new Error('Missing Lucide attribution');
const icons = Object.fromEntries([...source.matchAll(/<symbol id="ts-icon-([a-z0-9-]+)" viewBox="0 0 24 24">([\s\S]*?)<\/symbol>/g)]
  .map(([, name, geometry]) => {
    if (/<(?:script|foreignObject)|\bon\w+=|href=/i.test(geometry)) throw new Error('Unexpected SVG: ' + name);
    return [name, geometry.trim().replace(/>\s+</g, '><')];
  }));
if (!Object.keys(icons).length) throw new Error('Missing icons');
// Production minification can strip source comments. Ship the notice as a
// standalone public asset as well, so it is always included in dist-v2.
await mkdir(new URL('../public/third-party/', import.meta.url), { recursive: true });
await writeFile(new URL('../public/third-party/lucide-LICENSE.txt', import.meta.url), license.trim() + '\n', 'utf8');
await writeFile(new URL('../src/ui/next/next-icons.ts', import.meta.url), `/*! @license Generated by scripts/update-next-icons.mjs.\n${license.replaceAll('*/', '* /')}*/
const drawings = ${JSON.stringify(icons, null, 2)} as const;
export type NextIcon = keyof typeof drawings;
export function nextIcon(name: NextIcon): string {
  return '<svg data-next-icon="' + name + '" aria-hidden="true" focusable="false" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">' + drawings[name] + '</svg>';
}
`, 'utf8');
console.log('Bundled ' + Object.keys(icons).length + ' official local icons.');
