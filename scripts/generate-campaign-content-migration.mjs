import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const sources = [
  ["monster", "eng", "Monster_Manual-eng.json"], ["monster", "es", "Monster_Manual-es.json"],
  ["spell", "eng", "spells-eng.json"], ["spell", "es", "spells-es.json"],
  ["equipment", "eng", "equipment-eng.json"], ["equipment", "es", "equipment-es.json"],
];

function sqlText(value) { return `'${String(value).replaceAll("'", "''")}'`; }
function key(kind, language, name, index) {
  const hash = createHash("sha256").update(`${kind}\0${language}\0${name}\0${index}`).digest("hex").slice(0, 24);
  return `official:${kind}:${language}:${hash}`;
}

const rows = [];
for (const [kind, language, filename] of sources) {
  const parsed = JSON.parse(await readFile(resolve(root, filename), "utf8"));
  const values = Array.isArray(parsed) ? parsed : Object.values(parsed);
  values.forEach((payload, index) => {
    if (payload === null || typeof payload !== "object" || Array.isArray(payload)) return;
    const name = String(payload.name ?? payload.Name ?? "").trim();
    if (!name) return;
    const contentKey = key(kind, language, name, index);
    const tags = ["official", language, ...(payload.year ? [String(payload.year)] : [])];
    rows.push(`(${sqlText(kind)},${sqlText(contentKey)},${sqlText(name)},'official',array[${tags.map(sqlText).join(",")}],$content$${JSON.stringify(payload)}$content$::jsonb)`);
  });
}

const batches = [];
for (let index = 0; index < rows.length; index += 200) {
  batches.push(`insert into public.official_content_entries (kind, content_key, name, origin, tags, payload) values\n${rows.slice(index, index + 200).join(",\n")}\non conflict (kind, content_key) do update set name = excluded.name, tags = excluded.tags, payload = excluded.payload;`);
}

const sql = `-- Generated by scripts/generate-campaign-content-migration.mjs. Do not edit the catalog rows manually.
create table public.official_content_entries (
  kind text not null check (kind in ('spell', 'equipment', 'monster')),
  content_key text not null,
  name text not null,
  origin text not null default 'official' check (origin in ('official', 'gm', 'imported')),
  tags text[] not null default '{}',
  payload jsonb not null check (jsonb_typeof(payload) = 'object'),
  primary key (kind, content_key)
);

create table public.campaign_content_entries (
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  kind text not null check (kind in ('spell', 'equipment', 'monster', 'shop', 'checklist')),
  content_key text not null,
  name text not null check (char_length(btrim(name)) > 0),
  origin text not null check (origin in ('official', 'gm', 'imported')),
  tags text[] not null default '{}',
  payload jsonb not null check (jsonb_typeof(payload) = 'object'),
  revision bigint not null default 0 check (revision >= 0),
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default statement_timestamp(),
  updated_at timestamptz not null default statement_timestamp(),
  deleted_at timestamptz,
  primary key (campaign_id, kind, content_key)
);

create index campaign_content_entries_lookup_idx on public.campaign_content_entries(campaign_id, kind, lower(name)) where deleted_at is null;
alter table public.campaign_content_entries enable row level security;

create policy campaign_content_entries_select_member on public.campaign_content_entries
for select to authenticated using (public.is_campaign_member(campaign_id));
revoke all on table public.official_content_entries from anon, authenticated;
revoke all on table public.campaign_content_entries from anon, authenticated;
grant select on table public.campaign_content_entries to authenticated;

create or replace function public.can_manage_campaign_content(p_campaign_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.campaign_members member
    where member.campaign_id = p_campaign_id and member.user_id = auth.uid() and member.role in ('owner', 'gm')
  );
$$;
revoke all on function public.can_manage_campaign_content(uuid) from public;
grant execute on function public.can_manage_campaign_content(uuid) to authenticated;

${batches.join("\n\n")}

create or replace function public.seed_campaign_content(p_campaign_id uuid)
returns integer language plpgsql security definer set search_path = '' as $$
declare inserted_count integer;
begin
  if not public.can_manage_campaign_content(p_campaign_id) then
    raise exception using errcode = '42501', message = 'CAMPAIGN_GM_REQUIRED';
  end if;
  insert into public.campaign_content_entries (campaign_id, kind, content_key, name, origin, tags, payload, created_by, updated_by)
  select p_campaign_id, entry.kind, entry.content_key, entry.name, entry.origin, entry.tags, entry.payload, auth.uid(), auth.uid()
  from public.official_content_entries entry
  on conflict (campaign_id, kind, content_key) do nothing;
  get diagnostics inserted_count = row_count;
  return inserted_count;
end;
$$;

create or replace function public.seed_new_campaign_content()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.campaign_content_entries (campaign_id, kind, content_key, name, origin, tags, payload, created_by, updated_by)
  select new.id, entry.kind, entry.content_key, entry.name, entry.origin, entry.tags, entry.payload, new.owner_user_id, new.owner_user_id
  from public.official_content_entries entry;
  return new;
end;
$$;
create trigger seed_new_campaign_content_after_insert after insert on public.campaigns
for each row execute function public.seed_new_campaign_content();

insert into public.campaign_content_entries (campaign_id, kind, content_key, name, origin, tags, payload, created_by, updated_by)
select campaign.id, entry.kind, entry.content_key, entry.name, entry.origin, entry.tags, entry.payload, campaign.owner_user_id, campaign.owner_user_id
from public.campaigns campaign cross join public.official_content_entries entry
on conflict (campaign_id, kind, content_key) do nothing;

create or replace function public.save_campaign_content_entry(
  p_campaign_id uuid, p_kind text, p_content_key text, p_name text, p_origin text,
  p_tags text[], p_payload jsonb, p_expected_revision bigint default null
)
returns setof public.campaign_content_entries language plpgsql security definer set search_path = '' as $$
declare current_revision bigint;
begin
  if not public.can_manage_campaign_content(p_campaign_id) then raise exception using errcode = '42501', message = 'CAMPAIGN_GM_REQUIRED'; end if;
  if p_kind not in ('spell','equipment','monster','shop','checklist') or btrim(coalesce(p_content_key,'')) = '' or btrim(coalesce(p_name,'')) = '' then
    raise exception using errcode = '22023', message = 'INVALID_CONTENT_ENTRY';
  end if;
  if p_origin not in ('official','gm','imported') or p_payload is null or jsonb_typeof(p_payload) <> 'object' then
    raise exception using errcode = '22023', message = 'INVALID_CONTENT_ENTRY';
  end if;
  select revision into current_revision from public.campaign_content_entries
  where campaign_id = p_campaign_id and kind = p_kind and content_key = p_content_key;
  if current_revision is null then
    if p_expected_revision is not null then raise exception using errcode = 'P0001', message = 'CONTENT_REVISION_CONFLICT'; end if;
    if p_origin = 'official' and not exists (
      select 1 from public.official_content_entries official
      where official.kind = p_kind and official.content_key = p_content_key
    ) then raise exception using errcode = '22023', message = 'INVALID_OFFICIAL_PROVENANCE'; end if;
    return query insert into public.campaign_content_entries
      (campaign_id, kind, content_key, name, origin, tags, payload, created_by, updated_by)
      values (p_campaign_id, p_kind, p_content_key, btrim(p_name), p_origin, coalesce(p_tags,'{}'), p_payload, auth.uid(), auth.uid())
      returning *;
    return;
  end if;
  if p_expected_revision is null or current_revision <> p_expected_revision then raise exception using errcode = 'P0001', message = 'CONTENT_REVISION_CONFLICT'; end if;
  return query update public.campaign_content_entries entry set
    name = btrim(p_name), tags = coalesce(p_tags,'{}'), payload = p_payload,
    revision = entry.revision + 1, updated_by = auth.uid(), updated_at = statement_timestamp(), deleted_at = null
  where entry.campaign_id = p_campaign_id and entry.kind = p_kind and entry.content_key = p_content_key
  returning entry.*;
end;
$$;

create or replace function public.delete_campaign_content_entry(p_campaign_id uuid, p_kind text, p_content_key text, p_expected_revision bigint)
returns boolean language plpgsql security definer set search_path = '' as $$
declare affected integer;
begin
  if not public.can_manage_campaign_content(p_campaign_id) then raise exception using errcode = '42501', message = 'CAMPAIGN_GM_REQUIRED'; end if;
  update public.campaign_content_entries entry set deleted_at = statement_timestamp(), revision = entry.revision + 1,
    updated_by = auth.uid(), updated_at = statement_timestamp()
  where entry.campaign_id = p_campaign_id and entry.kind = p_kind and entry.content_key = p_content_key
    and entry.revision = p_expected_revision and entry.deleted_at is null;
  get diagnostics affected = row_count;
  if affected = 0 then raise exception using errcode = 'P0001', message = 'CONTENT_REVISION_CONFLICT'; end if;
  return true;
end;
$$;

revoke all on function public.seed_campaign_content(uuid) from public;
revoke all on function public.save_campaign_content_entry(uuid,text,text,text,text,text[],jsonb,bigint) from public;
revoke all on function public.delete_campaign_content_entry(uuid,text,text,bigint) from public;
grant execute on function public.seed_campaign_content(uuid) to authenticated;
grant execute on function public.save_campaign_content_entry(uuid,text,text,text,text,text[],jsonb,bigint) to authenticated;
grant execute on function public.delete_campaign_content_entry(uuid,text,text,bigint) to authenticated;

alter table public.campaign_content_entries replica identity full;
alter publication supabase_realtime add table public.campaign_content_entries;
`;

const output = resolve(root, "supabase/migrations/20260808000100_campaign_content_catalog.sql");
await writeFile(output, sql, "utf8");
process.stdout.write(`Generated ${rows.length} official entries in ${output}\n`);
